// Lane L4 (docs/updates/L4-CREDIT-SPEC.md): writes the ABIs of the attester and Credit contracts into the generated block
// of packages/shared/src/credit.ts, and their bytecode (plus the test stand-ins a local stack needs) into
// scripts/credit-generated.ts for local and test deployments. Reads Foundry artifacts from ../contracts/out
// (CREDIT_OUT overrides, for example a non-IR build).
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const out = process.env.CREDIT_OUT ?? join(here, "../../contracts/out");
const art = (file, name) => JSON.parse(readFileSync(join(out, file, `${name}.json`), "utf8"));
const lower = (n) => n[0].toLowerCase() + n.slice(1);

const contracts = [
  ["AttesterRegistry.sol", "AttesterRegistry"],
  ["AttesterFeeSplitter.sol", "AttesterFeeSplitter"],
  ["CreditPoolFactory.sol", "CreditPoolFactory"],
  ["CreditPool.sol", "CreditPool"],
  ["CreditRevenueRouter.sol", "CreditRevenueRouter"],
];
const START = "// ---- generated by scripts/credit-gen-abi.mjs: start";
const END = "// ---- generated by scripts/credit-gen-abi.mjs: end";
let block = `${START}\n`;
for (const [file, name] of contracts) block += `export const ${lower(name)}Abi = ${JSON.stringify(art(file, name).abi)} as const;\n`;
block += `${END}\n`;
const sharedPath = join(here, "../packages/shared/src/credit.ts");
let shared = readFileSync(sharedPath, "utf8");
const s = shared.indexOf(START);
shared = s >= 0 ? shared.slice(0, s) + block + shared.slice(shared.indexOf(END) + END.length + 1) : `${shared}\n${block}`;
writeFileSync(sharedPath, shared);

// implementations and the stand-ins of a local stack (development and test deployments only)
const local = [
  ...contracts,
  ["OrreryAttestor.sol", "OrreryAttestor"],
  ["Mocks.sol", "MockIdentityRegistry"],
  ["CreditBase.sol", "CreditUsdg"],
  ["CreditBase.sol", "CreditOrry"],
  ["CreditBase.sol", "CreditTreasury"],
  ["CreditBase.sol", "CreditOracle"],
];
let gen = "// generated by scripts/credit-gen-abi.mjs from ../contracts/out; do not edit\n";
for (const [file, name] of local) {
  const a = art(file, name);
  gen += `export const ${name} = { abi: ${JSON.stringify(a.abi)} as const, bytecode: "${a.bytecode.object}" as \`0x\${string}\` };\n`;
}
writeFileSync(join(here, "credit-generated.ts"), gen);
console.log(`credit ABIs: ${contracts.length} into shared, ${local.length} artifacts into scripts/credit-generated.ts`);
