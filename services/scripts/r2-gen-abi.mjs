// Lane L3 (docs/updates/L3-R2-SPEC.md): writes the R2 interface ABIs into the generated block of
// packages/shared/src/r2.ts, and the implementations' ABIs and bytecode (plus the test stand-ins a local stack needs)
// into scripts/r2-generated.ts for local and test deployments. Reads Foundry artifacts from ../contracts/out.
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const out = join(here, "../../contracts/out");
// Shield V2 builds with the legacy profile (foundry.toml compilation restrictions): prefer that artifact when it exists,
// since forge may also leave a via-IR one that is over the size limit.
const art = (file, name) => {
  const legacy = join(out, file, `${name}.legacy.json`);
  const preferLegacy = file === "OrreryShield.sol" || file === "HonkVerifier.sol";
  return JSON.parse(readFileSync(preferLegacy && existsSync(legacy) ? legacy : join(out, file, `${name}.json`), "utf8"));
};
const lower = (n) => n[0].toLowerCase() + n.slice(1);

const interfaces = [
  ["IPrediction.sol", "IPredictionMarketFactory"],
  ["IPrediction.sol", "IPredictionMarket"],
  ["ILimitOrderBook.sol", "ILimitOrderBook"],
  ["IOrryPaymaster.sol", "IOrryPaymaster"],
  ["IShield.sol", "IOrreryShield"],
];
const START = "// ---- generated by scripts/r2-gen-abi.mjs: start";
const END = "// ---- generated by scripts/r2-gen-abi.mjs: end";
let block = `${START}\n`;
for (const [file, name] of interfaces) block += `export const ${lower(name)}Abi = ${JSON.stringify(art(file, name).abi)} as const;\n`;
block += `${END}\n`;
const sharedPath = join(here, "../packages/shared/src/r2.ts");
let shared = readFileSync(sharedPath, "utf8");
const s = shared.indexOf(START);
shared = s >= 0 ? shared.slice(0, s) + block + shared.slice(shared.indexOf(END) + END.length + 1) : `${shared}\n${block}`;
writeFileSync(sharedPath, shared);

// implementations and the stand-ins of a local stack (development and test deployments only)
const deployables = [
  ["PredictionMarketFactory.sol", "PredictionMarketFactory"],
  ["LimitOrderBook.sol", "LimitOrderBook"],
  ["OrryPaymaster.sol", "OrryPaymaster"],
  ["FeeTiers.sol", "FeeTiers"],
  ["OrryPriceOracle.sol", "OrryPriceOracle"],
  ["MarketFactory.sol", "MarketFactory"],
  ["MarketMocks.sol", "MockStock"],
  ["MarketMocks.sol", "MockAccessRegistry"],
  ["MarketMocks.sol", "MockUsdg"],
  ["MarketMocks.sol", "MockFeed"],
  ["MarketMocks.sol", "MockEarningStaking"],
  ["MarketMocks.sol", "OracleHookStandIn"],
  ["StakeMocks.sol", "MockOrry"],
  ["PoolModifyLiquidityTest.sol", "PoolModifyLiquidityTest"],
  ["PoolSwapTest.sol", "PoolSwapTest"],
  ["PaymasterBase.sol", "MockEntryPoint"],
  ["OrreryShield.sol", "OrreryShield"],
  ["HonkVerifier.sol", "ZKTranscriptLib"],
  ["HonkVerifier.sol", "RelationsLib"],
];
// the generated verifier calls two external libraries; its bytecode is linked at deployment (scripts/r2-stack.ts)
const linked = [["HonkVerifier.sol", "HonkVerifier"]];
let gen = "// Generated by scripts/r2-gen-abi.mjs from contracts/out. Development and test deployments only.\n";
for (const [file, name] of deployables) {
  const a = art(file, name);
  if (a.bytecode.object.includes("__$")) throw new Error(`${name} needs library linking`);
  gen += `export const ${lower(name)}Abi = ${JSON.stringify(a.abi)} as const;\n`;
  gen += `export const ${lower(name)}Bytecode = "${a.bytecode.object}" as const;\n`;
}
for (const [file, name] of linked) {
  const a = art(file, name);
  const refs = Object.entries(a.bytecode.linkReferences).flatMap(([src, libs]) =>
    Object.entries(libs).map(([lib, at]) => ({ lib, src, starts: at.map((x) => x.start) })),
  );
  gen += `export const ${lower(name)}Abi = ${JSON.stringify(a.abi)} as const;\n`;
  gen += `export const ${lower(name)}Bytecode = "${a.bytecode.object}" as const;\n`;
  gen += `export const ${lower(name)}LinkReferences = ${JSON.stringify(refs)} as const;\n`;
}
writeFileSync(join(here, "r2-generated.ts"), gen);
console.log(`r2 ABIs: ${interfaces.length} interfaces into shared/src/r2.ts, ${deployables.length} deployables into scripts/r2-generated.ts`);
