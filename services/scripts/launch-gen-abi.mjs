// Lane L5 (docs/updates/L5-LAUNCH-SPEC.md): writes the Agent Launch interface ABIs into the generated block of
// packages/shared/src/launch.ts, and the implementations' ABIs and bytecode (plus the test stand-ins a local stack needs)
// into scripts/launch-generated.ts for local and test deployments. Reads Foundry artifacts from ../contracts/out.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const out = join(here, "../../contracts/out");
const art = (file, name) => JSON.parse(readFileSync(join(out, file, `${name}.json`), "utf8"));
const lower = (n) => n[0].toLowerCase() + n.slice(1);

const interfaces = [
  ["IAgentLaunch.sol", "IAgentLaunch"],
  ["ISpokeHook.sol", "ISpokeHook"],
  ["SpokeRouter.sol", "SpokeRouter"],
];
const START = "// ---- generated by scripts/launch-gen-abi.mjs: start";
const END = "// ---- generated by scripts/launch-gen-abi.mjs: end";
let block = `${START}\n`;
for (const [file, name] of interfaces) block += `export const ${lower(name)}Abi = ${JSON.stringify(art(file, name).abi)} as const;\n`;
block += `${END}\n`;
const sharedPath = join(here, "../packages/shared/src/launch.ts");
let shared = readFileSync(sharedPath, "utf8");
const s = shared.indexOf(START);
shared = s >= 0 ? shared.slice(0, s) + block + shared.slice(shared.indexOf(END) + END.length + 1) : `${shared}\n${block}`;
writeFileSync(sharedPath, shared);

// implementations and the stand-ins of a local stack (development and test deployments only)
const deployables = [
  ["AgentLaunch.sol", "AgentLaunch"],
  ["SpokeHook.sol", "SpokeHook"],
  ["SpokeRouter.sol", "SpokeRouter"],
  ["AgentCoin.sol", "AgentCoin"],
  ["OrryStaking.sol", "OrryStaking"],
  ["OrryPriceOracle.sol", "OrryPriceOracle"],
  ["StakeMocks.sol", "MockOrry"],
  ["Mocks.sol", "MockIdentityRegistry"],
  ["LaunchMocks.sol", "MockAttestorL5"],
  ["LaunchMocks.sol", "MockPolicyModuleL5"],
  ["LaunchMocks.sol", "MockTreasuryL5"],
  ["LaunchMocks.sol", "MockEarnVaultL5"],
  ["CommunityMocks.sol", "MockOrryPrice"],
  ["PoolSwapTest.sol", "PoolSwapTest"],
];
let gen = "// Generated by scripts/launch-gen-abi.mjs from contracts/out. Development and test deployments only.\n";
for (const [file, name] of deployables) {
  const a = art(file, name);
  if (a.bytecode.object.includes("__$")) throw new Error(`${name} needs library linking`);
  gen += `export const ${lower(name)}Abi = ${JSON.stringify(a.abi)} as const;\n`;
  gen += `export const ${lower(name)}Bytecode = "${a.bytecode.object}" as const;\n`;
}
writeFileSync(join(here, "launch-generated.ts"), gen);
console.log(`launch ABIs: ${interfaces.length} interfaces into shared/src/launch.ts, ${deployables.length} deployables into scripts/launch-generated.ts`);
