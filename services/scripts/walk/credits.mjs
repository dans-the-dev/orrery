// Walk: Credits on the development network. A key by signature, a signed check on the demo agent's signer, a credit
// pack over x402, and the balance after each step.
import { createRequire } from "node:module";
import { homedir } from "node:os";
import { join } from "node:path";
import { attachWallet } from "./wallet.mjs";
const require = createRequire("/home/dand/Projects/blockchain/matriks-destiny/package.json");
const { chromium } = require("playwright-core");
const [base = "https://orrery-dev.vercel.app", shots = "."] = process.argv.slice(2);
const SIGNER = process.env.WALK_SIGNER ?? "0x4C4bd566516eAe906ad5029317758C58E4A2a606";
const browser = await chromium.launch({ executablePath: "/usr/bin/google-chrome" });
const page = await (await browser.newContext({ viewport: { width: 1440, height: 1000 } })).newPage();
const errors = [];
page.on("console", (m) => m.type() === "error" && !m.text().includes("_rsc") && errors.push(m.text().slice(0, 200)));
const w = await attachWallet(page, { keyFile: join(homedir(), ".secrets/orrery/46630-walk.json"), rpc: process.env.WALK_RPC ?? "https://robinhood-sepolia-rpc.publicnode.com", chainId: Number(process.env.WALK_CHAIN ?? 46630) });
const say = (s) => console.log(s);
const notice = async () => (await page.locator(".notice").last().innerText().catch(() => "")).trim();
await page.goto(base + "/credits", { waitUntil: "networkidle" });
await page.waitForTimeout(2000);
await page.getByRole("button", { name: "Get my API key" }).click();
await page.locator(".key-box").waitFor({ timeout: 30000 });
say(`1 key issued: ${(await page.locator(".key-box").innerText()).slice(0, 6)}… · ${await notice()}`);
await page.getByRole("button", { name: "Show balance" }).click();
await page.waitForTimeout(2500);
say(`2 balance: ${(await page.locator(".kv").last().innerText()).replace(/\n/g, " · ")}`);
await page.getByLabel("Paying address").fill(SIGNER);
await page.getByRole("button", { name: "Run signed check" }).click();
await page.waitForTimeout(8000);
const result = await page.locator(".kv").last().innerText().catch(() => "");
say(`3 signed check: ${result.replace(/\n/g, " · ").slice(0, 300)}`);
await page.getByRole("button", { name: /^Buy .* credits$/ }).click();
for (let i = 0; i < 40 && !/Credits added|not accepted|did not finish/.test(await notice()); i++) await page.waitForTimeout(1500);
say(`4 credit pack: ${await notice()}`);
await page.getByRole("button", { name: "Show balance" }).click();
await page.waitForTimeout(2500);
say(`5 balance: ${(await page.locator(".kv").last().innerText()).replace(/\n/g, " · ")}`);
await page.screenshot({ path: join(shots, "walk-credits.png"), fullPage: true });
say(`wallet calls: ${[...new Set(w.log)].join(", ")}`);
say(errors.length ? `console errors: ${[...new Set(errors)].join(" | ")}` : "no console errors");
await browser.close();
